def _collapse_athena_prefixes(prefixes: Optional[list[str]]) -> tuple[Optional[str], Optional[str]]:
    """Collapse a possibly over-split prefix list back to (catalog, schema).

    Athena always has exactly 2 logical prefix levels: [catalog, schema].
    When a catalog name contains '/' (e.g. 's3tablescatalog/bucket_name'),
    DatasetIdentifier.parse() splits it into extra elements. This helper
    rejoins everything except the last element as the catalog and treats
    the last element as the schema.
    """
    if not prefixes:
        return None, None
    if len(prefixes) == 1:
        return prefixes[0], None
    return "/".join(prefixes[:-1]), prefixes[-1]


class AthenaDataSourceImpl(DataSourceImpl, model_class=AthenaDataSourceModel):
    def __init__(self, data_source_model: AthenaDataSourceModel, connection: Optional[DataSourceConnection] = None):
        super().__init__(data_source_model=data_source_model, connection=connection)

    def _create_sql_dialect(self) -> SqlDialect:
        return AthenaSqlDialect(get_table_storage_location=self.table_s3_location)

    def _create_data_source_connection(self) -> DataSourceConnection:
        return AthenaDataSourceConnection(
            name=self.data_source_model.name, connection_properties=self.data_source_model.connection_properties
        )

    def execute_update(self, sql: str, log_query: bool = True) -> int:
        result: int = super().execute_update(sql, log_query=log_query)
        # Athena requires some extra cleanup for a drop table or drop schema statement.
        if sql.startswith("DROP TABLE "):
            # We assume that the statement is generated by the SQL Dialect, so we can parse the table name from it.
            qualified_table_name = self.__parse_table_name_from_drop_table_sql(sql)
            table_location = self.table_s3_location(
                qualified_table_name, lowercase=True
            )  # Athena table names are always lowercase, so the location should be lowercase as well.
            self._delete_s3_files(table_location)
        elif sql.startswith("DROP SCHEMA"):
            schema_name = self.__parse_schema_name_from_drop_schema_sql(sql)
            schema_location = self.table_s3_location(schema_name, lowercase=False)  # Schema should not be lowercased.
            self._delete_s3_files(schema_location)
        return result

    def table_s3_location(self, qualified_table_name: str, lowercase: bool = True) -> str:
        table_part_for_location = qualified_table_name.replace(".", "/").replace('"', "").replace("`", "")
        if lowercase:  # Athena table names are always lowercase, so the location should be lowercase as well.
            table_part_for_location = table_part_for_location.lower()
        location = f"{self.connection.athena_staging_dir}/{table_part_for_location}/"
        return location

    def __parse_schema_name_from_drop_schema_sql(self, sql: str) -> str:
        remaining_sql = sql[len("DROP SCHEMA ") :].strip()
        if remaining_sql.startswith("IF EXISTS "):
            remaining_sql = remaining_sql[len("IF EXISTS ") :].strip()
        if remaining_sql.endswith(";"):
            remaining_sql = remaining_sql[:-1]
        if remaining_sql.endswith(" CASCADE"):
            remaining_sql = remaining_sql[: -len(" CASCADE")]
        return remaining_sql.strip()

    def __parse_table_name_from_drop_table_sql(self, sql: str) -> str:
        remaining_sql = sql[len("DROP TABLE ") :].strip()
        if remaining_sql.startswith("IF EXISTS "):
            remaining_sql = remaining_sql[len("IF EXISTS ") :].strip()
        if remaining_sql.endswith(";"):
            remaining_sql = remaining_sql[:-1]
        return remaining_sql.strip()

    def _delete_s3_files(self, directory: str):
        """
        Deletes all files under a given directory in S3.
        """
        logger.debug(f"Deleting all s3 files under {directory}")
        bucket = self._extract_s3_bucket(directory)
        folder = self._extract_s3_folder(directory)
        s3_client = self._create_s3_client()
        response = s3_client.list_objects_v2(Bucket=bucket, Prefix=folder)
        object_keys = self._extract_object_keys(response)
        logger.debug(f"Found {len(object_keys)} to be deleted")
        max_objects = 200
        assert len(object_keys) < max_objects, (
            f"This method is intended for tests and hence limited to a maximum of {max_objects} objects, "
            f"{len(object_keys)} objects exceeds the limit."
        )
        if len(object_keys) > 0:
            response: dict = s3_client.delete_objects(Bucket=bucket, Delete={"Objects": object_keys})
            deleted_list = response.get("Deleted") if isinstance(response, dict) else None
            deleted_count = (
                len(deleted_list) if isinstance(deleted_list, list) else "Unknown aws delete objects response"
            )
            logger.debug(f"Deleted {deleted_count}")

    def _create_s3_client(self) -> boto3.client:
        self.filter_false_positive_boto3_warning()
        aws_credentials = self.connection.aws_credentials
        aws_credentials = aws_credentials.resolve_role("soda_sql_test_cleanup")
        return boto3.client(
            "s3",
            region_name=aws_credentials.region_name,
            aws_access_key_id=aws_credentials.access_key_id,
            aws_secret_access_key=aws_credentials.secret_access_key,
            aws_session_token=aws_credentials.session_token,
        )

    def _extract_object_keys(self, response: dict) -> list[dict]:
        object_keys = []
        if "Contents" in response:
            objects = response["Contents"]
            for summary in objects:
                key = summary["Key"]
                object_keys.append({"Key": key})
        return object_keys

    S3_URI_PATTERN = r"(^s3://)([^/]*)/(.*$)"

    @classmethod
    def _extract_s3_folder(cls, uri):
        return re.search(cls.S3_URI_PATTERN, uri).group(3)

    @classmethod
    def _extract_s3_bucket(cls, uri):
        return re.search(cls.S3_URI_PATTERN, uri).group(2)

    def filter_false_positive_boto3_warning(self):
        # see
        # https://github.com/boto/boto3/issues/454#issuecomment-380900404
        import warnings

        warnings.filterwarnings("ignore", category=ResourceWarning, message="unclosed <ssl.SSLSocket")
        warnings.filterwarnings("ignore", category=DeprecationWarning, message="the imp module is deprecated")
        warnings.filterwarnings("ignore", category=DeprecationWarning, message="Using or importing the ABCs")

    def verify_if_table_exists(self, prefixes: list[str], table_name: str) -> bool:
        fully_qualified_table_names: list[FullyQualifiedTableName] = self._get_fully_qualified_table_names(
            prefixes=prefixes, table_name=table_name
        )
        return any(
            fully_qualified_table_name.table_name.lower()
            == table_name.lower()  # Athena table names are always lowercase
            for fully_qualified_table_name in fully_qualified_table_names
        )


class AthenaSqlDialect(SqlDialect, sqlglot_dialect="athena"):
    SUPPORTS_DROP_TABLE_CASCADE = False
    # Athena (Trino engine) requires OFFSET before LIMIT.
    OFFSET_BEFORE_LIMIT: bool = True
    SUPPORTS_DATA_PLANE_STATEMENTS = True

    # Primary-key introspection stays opt-out (supports_primary_keys inherits False from the
    # base dialect): Athena runs over Glue/Hive-style catalogs that neither declare primary keys
    # in CREATE TABLE nor expose them through information_schema constraint views.

    SODA_DATA_TYPE_SYNONYMS = (
        (SodaDataTypeName.TEXT, SodaDataTypeName.VARCHAR),
        (SodaDataTypeName.NUMERIC, SodaDataTypeName.DECIMAL),
        (SodaDataTypeName.TIMESTAMP_TZ, SodaDataTypeName.TIMESTAMP),
        (SodaDataTypeName.TIME, SodaDataTypeName.VARCHAR),
    )

    def __init__(self, get_table_storage_location: Optional[Callable[[str], str]] = None):
        super().__init__()
        self.get_table_storage_location = get_table_storage_location

    def quote_for_ddl(self, identifier: Optional[str]) -> Optional[str]:
        """Athena DDL uses Hive parser (backticks) while DML uses Trino parser (double quotes)."""
        return f"`{identifier}`" if isinstance(identifier, str) and len(identifier) > 0 else None

    @staticmethod
    def _normalize_prefix(dataset_prefix: Optional[list[str]]) -> Optional[list[str]]:
        """Adapt _collapse_athena_prefixes to the [catalog, schema] list shape the base dialect expects."""
        if not dataset_prefix:
            return dataset_prefix
        catalog, schema = _collapse_athena_prefixes(dataset_prefix)
        if schema is None:
            return [catalog] if catalog is not None else dataset_prefix
        return [catalog, schema]

    # The base reads fixed indices into prefixes. That doesn't work for Athena: a catalog
    # containing '/' is over-split by DatasetIdentifier.parse() into an arbitrary number of
    # prefix elements, so the tail is collapsed back into a single catalog name.
    def extract_database_from_prefix(self, prefixes: list[str]) -> Optional[str]:
        catalog, _ = _collapse_athena_prefixes(prefixes)
        return catalog

    def extract_schema_from_prefix(self, prefixes: list[str]) -> Optional[str]:
        _, schema = _collapse_athena_prefixes(prefixes)
        return schema

    def _build_qualified_quoted_dataset_name(self, dataset_name: str, dataset_prefix: Optional[list[str]]) -> str:
        return super()._build_qualified_quoted_dataset_name(dataset_name, self._normalize_prefix(dataset_prefix))

    def qualify_dataset_name(self, dataset_prefix: list[str], dataset_name: str) -> str:
        return super().qualify_dataset_name(self._normalize_prefix(dataset_prefix), dataset_name)

    def default_casify(self, identifier: str) -> str:
        return identifier.lower()

    def metadata_casify(self, identifier: str) -> str:
        return identifier.lower()

    def get_data_source_data_type_name_by_soda_data_type_names(self) -> dict:
        """
        Maps DBDataType names to data source type names.
        """
        return {
            SodaDataTypeName.CHAR: "char",
            SodaDataTypeName.VARCHAR: "varchar",
            SodaDataTypeName.TEXT: "varchar",
            SodaDataTypeName.SMALLINT: "smallint",
            SodaDataTypeName.INTEGER: "integer",
            SodaDataTypeName.BIGINT: "bigint",
            SodaDataTypeName.DECIMAL: "decimal",
            SodaDataTypeName.NUMERIC: "decimal",
            SodaDataTypeName.FLOAT: "float",
            SodaDataTypeName.DOUBLE: "double",
            SodaDataTypeName.DATE: "date",
            SodaDataTypeName.TIME: "varchar",  # Athena does not support time data type, for time specifically, it should be formatted as a string!
            SodaDataTypeName.TIMESTAMP: "timestamp",
            SodaDataTypeName.TIMESTAMP_TZ: "timestamp",
            SodaDataTypeName.BOOLEAN: "boolean",
        }

    # AI generated
    def get_soda_data_type_name_by_data_source_data_type_names(self) -> dict[str, SodaDataTypeName]:
        """
        Maps native Athena data source type names to SodaDataTypeName's
        """
        return {
            # Character/String types
            "char": SodaDataTypeName.CHAR,
            "varchar": SodaDataTypeName.VARCHAR,
            "string": SodaDataTypeName.TEXT,
            "character varying": SodaDataTypeName.VARCHAR,
            # Integer types
            "tinyint": SodaDataTypeName.SMALLINT,
            "smallint": SodaDataTypeName.SMALLINT,
            "integer": SodaDataTypeName.INTEGER,
            "int": SodaDataTypeName.INTEGER,
            "bigint": SodaDataTypeName.BIGINT,
            # Decimal/Numeric types
            "decimal": SodaDataTypeName.DECIMAL,
            "numeric": SodaDataTypeName.NUMERIC,
            # Floating point types
            "float": SodaDataTypeName.FLOAT,
            "real": SodaDataTypeName.FLOAT,
            "double": SodaDataTypeName.DOUBLE,
            # Date/Time types
            "date": SodaDataTypeName.DATE,
            "timestamp": SodaDataTypeName.TIMESTAMP,
            # Boolean type
            "boolean": SodaDataTypeName.BOOLEAN,
            "bool": SodaDataTypeName.BOOLEAN,
        }

    def _get_data_type_name_synonyms(self) -> list[list[str]]:
        # Implements data type synonyms
        # Each list should represent a list of synonyms
        return [
            ["varchar", "character varying", "string"],
            ["decimal"],
            ["timestamp"],
        ]

    def get_data_source_type_names_by_test_type_names(self) -> dict[str, str]:
        raise NotImplementedError()

    def quote_column(self, column_name: str) -> str:
        return f'"{column_name}"'

    def _build_column_sql(self, column: COLUMN) -> str:
        table_alias_sql: str = f"{self.quote_default(column.table_alias)}." if column.table_alias else ""
        # We need to check if the column name is a string (then quote it ourselves) or a SqlExpression (then let it be compiled)
        if isinstance(column.name, str):
            column_sql = f'"{column.name}"'
        else:
            column_sql = self.build_expression_sql(column.name)
        return f"{table_alias_sql}{column_sql}"

    def literal_datetime(self, datetime: datetime):
        return f"From_iso8601_timestamp('{datetime.isoformat()}')"

    def literal_datetime_with_tz(self, datetime: datetime):
        # Can be overloaded if the subclass does not support timezones (may have to do conversion yourself)
        # We assume that all timestamps are stored in UTC.
        # See Fabric for an example
        return self.literal_datetime(datetime)

    def supports_varchar_length(self) -> bool:
        return False

    def sql_expr_timestamp_literal(self, datetime_in_iso8601: str) -> str:
        return f"CAST(From_iso8601_timestamp('{datetime_in_iso8601}') AS timestamp)"

    def sql_expr_timestamp_add_day(self, timestamp_literal: str) -> str:
        return f"{timestamp_literal} + interval '1' day"

    # Lowercase singular unit names for date_add (Athena engine v3 functions are
    # Trino's, https://docs.aws.amazon.com/athena/latest/ug/functions-env3.html).
    _TIME_BUCKET_UNIT_NAMES: dict = {
        "weeks": "week",
        "days": "day",
        "hours": "hour",
        "seconds": "second",
    }

    def _build_time_delta_sql(self, time_delta: TIME_DELTA) -> str:
        """Seconds date_diff divided by the float seconds-per-interval, cast to
        int. The cast matters: floor() returns double on the Trino engine and
        date_add's value argument must be integer-typed."""
        start_sql: str = self.build_expression_sql(time_delta.start)
        end_sql: str = self.build_expression_sql(time_delta.end)
        secs_per_interval: float = seconds_per_time_bucket(time_delta.unit, time_delta.count) / 1.0
        return f"cast(floor(date_diff('second', {start_sql}, {end_sql}) / {secs_per_interval}) as int)"

    def _build_add_interval_sql(self, add_interval: ADD_INTERVAL) -> str:
        timestamp_sql: str = self.build_expression_sql(add_interval.timestamp)
        count_sql: str = self.build_expression_sql(add_interval.count_expression)
        unit_name: str = self._TIME_BUCKET_UNIT_NAMES[add_interval.unit]
        return f"date_add('{unit_name}', {count_sql}, {timestamp_sql})"

    def _build_percentile_within_group_sql(self, percentile_within_group: PERCENTILE_WITHIN_GROUP) -> str:
        """The Trino-based Athena engine does not accept the base WITHIN GROUP
        form; approx_percentile is its percentile aggregate."""
        expression_sql: str = self.build_expression_sql(percentile_within_group.expression)
        return f"approx_percentile({expression_sql}, {percentile_within_group.percentile})"

    def _build_cast_sql(self, cast: CAST) -> str:
        """Athena splits its SQL across two parsers: DDL is Hive (FLOAT is the
        float32 type; REAL does not exist) while DML/expressions are Trino
        (REAL is the float32 type; FLOAT does not exist). The canonical type
        map serves DDL (see get_data_source_data_type_name_by_soda_data_type_names
        and its create-table consumers), so canonical FLOAT casts must render
        the Trino name here instead."""
        if cast.to_type == SodaDataTypeName.FLOAT:
            return f"CAST({self.build_expression_sql(cast.expression)} AS real)"
        return super()._build_cast_sql(cast)

    def build_create_table_sql(
        self, create_table: CREATE_TABLE | CREATE_TABLE_IF_NOT_EXISTS, add_semicolon: bool = True
    ) -> str:
        if self.get_table_storage_location is None:
            raise ValueError("get_table_storage_location function must be provided to build create table SQL")
        if create_table.transactional and self.SUPPORTS_DATA_PLANE_STATEMENTS:
            return self._build_iceberg_create_table_sql(create_table, add_semicolon)
        create_table_sql = self._build_create_table_statement_sql(create_table)

        create_table_sql = (
            create_table_sql
            + "(\n"
            + ",\n".join([self._build_create_table_column(column) for column in create_table.columns])
            + "\n)"
        )
        location = self.get_table_storage_location(create_table.fully_qualified_table_name)
        create_table_sql = create_table_sql + "\nSTORED AS PARQUET"
        create_table_sql = create_table_sql + f"\nLOCATION '{location}'"
        return create_table_sql + (";" if add_semicolon else "")

    def _build_create_table_statement_sql(self, create_table: CREATE_TABLE | CREATE_TABLE_IF_NOT_EXISTS) -> str:
        if_not_exists_sql: str = "IF NOT EXISTS" if isinstance(create_table, CREATE_TABLE_IF_NOT_EXISTS) else ""
        table_name: str = self._convert_fqn_for_ddl(create_table.fully_qualified_table_name)
        create_table_sql: str = f"CREATE EXTERNAL TABLE {if_not_exists_sql} {table_name} "
        return create_table_sql

    def _build_create_table_column_type(self, create_table_column: CREATE_TABLE_COLUMN) -> str:
        assert isinstance(create_table_column.type, SqlDataType)
        # We need to check for text datatypes if there is a length parameter. If there is, use varchar, otherwise use string.
        # This only applies to the create table statement, not the schema check. For the schema check we need to use the original data type (varchar), but without length.
        if create_table_column.type.name == "varchar" and create_table_column.type.character_maximum_length is None:
            return "string"
        if create_table_column.type.name == "char" and create_table_column.type.character_maximum_length is None:
            return "char(1)"
        # Delegate to the base implementation so the type-aware and dialect-level
        # safeguards (which strip e.g. `timestamp(2)` down to `timestamp` since
        # supports_data_type_datetime_precision returns False for athena) apply.
        return super()._build_create_table_column_type(create_table_column)

    def _is_not_null_ddl_supported(self) -> bool:
        return False

    def supports_data_type_character_maximum_length(self) -> bool:
        return True

    def supports_data_type_numeric_precision(self) -> bool:
        return True

    def supports_data_type_numeric_scale(self) -> bool:
        return True

    def supports_data_type_datetime_precision(self) -> bool:
        return False  # Technically it is supported, but we can't modify it in a CREATE TABLE statement (always defaults to 3)

    def column_data_type_max_length(self) -> Optional[str]:
        """Athena supports this but it's not in information schema."""
        return None

    def column_data_type_numeric_precision(self) -> Optional[str]:
        """Athena supports this but it's not in information schema."""
        return None

    def column_data_type_numeric_scale(self) -> Optional[str]:
        """Athena supports this but it's not in information schema."""
        return None

    def format_metadata_data_type(self, data_type: str) -> str:
        """Athena sometimes modifies data types to include precision (e.g. TIMESTAMP as TIMESTAMP(3)) in column metadata

        We don't want data type comparisons to fail, so strip this extra information.
        """
        paranthesis_index = data_type.find("(")
        if paranthesis_index != -1:
            return data_type[:paranthesis_index]
        return data_type

    def data_type_has_parameter_character_maximum_length(self, data_type_name) -> bool:
        return self.format_metadata_data_type(data_type_name).lower() in ["varchar", "char"]

    def data_type_has_parameter_numeric_precision(self, data_type_name) -> bool:
        return self.format_metadata_data_type(data_type_name).lower() in ["decimal"]

    def data_type_has_parameter_numeric_scale(self, data_type_name) -> bool:
        return self.format_metadata_data_type(data_type_name).lower() in ["decimal"]

    def data_type_has_parameter_datetime_precision(self, data_type_name) -> bool:
        return self.format_metadata_data_type(data_type_name).lower() in ["timestamp", "time"]

    def supports_case_sensitive_column_names(self) -> bool:
        return False  # Athena does not support case sensitive names: everything is lowercase.

    def extract_character_maximum_length(self, row: Tuple[Any, ...], columns: list[Tuple[Any, ...]]) -> Optional[int]:
        # Varchars are a special case, they may contain a length parameter, but not always!
        data_type_name: str = self.extract_data_type_name(row, columns)
        formatted_data_type_name: str = self.format_metadata_data_type(data_type_name)
        if not self.data_type_has_parameter_character_maximum_length(data_type_name):
            return None
        # extract value from inside parentheses
        data_type_tuple = data_type_name[len(formatted_data_type_name) + 1 : -1].split(",")
        if data_type_tuple[0].isnumeric():
            return int(data_type_tuple[0])
        return None

    def extract_numeric_precision(self, row: Tuple[Any, ...], columns: list[Tuple[Any, ...]]) -> Optional[int]:
        data_type_name: str = self.extract_data_type_name(row, columns)
        if not self.data_type_has_parameter_numeric_precision(data_type_name):
            return None

        formatted_data_type_name: str = self.format_metadata_data_type(data_type_name)
        data_type_tuple = data_type_name[len(formatted_data_type_name) + 1 : -1].split(",")
        return int(data_type_tuple[0])

    def extract_numeric_scale(self, row: Tuple[Any, ...], columns: list[Tuple[Any, ...]]) -> Optional[int]:
        data_type_name: str = self.extract_data_type_name(row, columns)
        formatted_data_type_name: str = self.format_metadata_data_type(data_type_name)
        if not self.data_type_has_parameter_numeric_scale(data_type_name):
            return None

        data_type_tuple = data_type_name[len(formatted_data_type_name) + 1 : -1].split(",")
        return int(data_type_tuple[1])

    def supports_datetime_microseconds(self) -> bool:
        return False

    def get_max_sql_statement_length(self) -> int:
        return 262144

    def _build_string_hash_sql(self, string_hash: STRING_HASH) -> str:
        return f"to_hex(md5(to_utf8({self.build_expression_sql(string_hash.expression)})))"

    def _build_alter_table_add_column_sql(
        self, alter_table: ALTER_TABLE_ADD_COLUMN, add_semicolon: bool = True, add_parenthesis: bool = False
    ) -> str:
        # Athena ALTER TABLE uses the Hive parser (backticks, "ADD COLUMNS", parentheses).
        table_name: str = self._convert_fqn_for_ddl(alter_table.fully_qualified_table_name)
        column_name_quoted: str = self._quote_column_for_create_table(alter_table.column.name)
        column_type_sql: str = self._build_create_table_column_type(alter_table.column)
        return f"ALTER TABLE {table_name} ADD COLUMNS ({column_name_quoted} {column_type_sql});"

    def drop_column_supported(self) -> bool:
        return (
            False  # It MAY be possible to drop columns in Athena by using REPLACE COLUMNS, but we don't support it yet.
        )

    def build_insert_into_via_select_sql(
        self, insert_into_via_select: INSERT_INTO_VIA_SELECT, add_semicolon: bool = True
    ) -> str:
        insert_into_sql: str = f"INSERT INTO {insert_into_via_select.fully_qualified_table_name}\n"
        insert_into_sql += self._build_insert_into_columns_sql(insert_into_via_select) + "\n"
        insert_into_sql += (
            "\n"
            + self.build_select_sql(insert_into_via_select.select_elements, add_semicolon=False)
            + "\n"  # Athena does not like the parenthesis around the select statement.
        )
        return insert_into_sql + (";" if add_semicolon else "")

    ###
    # Data plane statements
    ###
    # Row-level UPDATE, DELETE and MERGE run on an Iceberg table only, which CREATE TABLE creates for a
    # transactional table; Athena refuses them on a Hive table. Athena has no transactions, so there is no
    # read-only transaction to begin or roll back: every statement commits on its own. Nor does it create
    # an index or refresh statistics on request. Those render None; CREATE SCHEMA is the base statement.

    # MERGE names its incoming rows; SOURCE_COLUMN renders as this alias.
    _MERGE_SOURCE_ALIAS = "src"
    _MERGE_DEFAULT_TARGET_ALIAS = "tgt"

    # Athena's Iceberg DDL refuses CHAR, and INTEGER, which it names INT; Iceberg has no bounded VARCHAR,
    # TINYINT, SMALLINT, TIME or zoned timestamp. A timestamp column is timestamp(6) whatever precision it
    # declares.
    _ICEBERG_COLUMN_TYPE_NAMES: dict[str, str] = {
        "char": "string",
        "varchar": "string",
        "integer": "int",
        "tinyint": "int",
        "smallint": "int",
        "time": "string",
        "timestamp": "timestamp",
        "timestamp with time zone": "timestamp",
    }

    def _build_iceberg_create_table_sql(
        self, create_table: CREATE_TABLE | CREATE_TABLE_IF_NOT_EXISTS, add_semicolon: bool
    ) -> str:
        """Without NOT NULL or a primary key, which Athena's Iceberg DDL lacks."""
        if_not_exists_sql: str = " IF NOT EXISTS" if isinstance(create_table, CREATE_TABLE_IF_NOT_EXISTS) else ""
        table_name: str = self._convert_fqn_for_ddl(create_table.fully_qualified_table_name)
        columns_sql: str = ",\n".join(
            self._build_iceberg_create_table_column(column) for column in create_table.columns
        )
        location: str = self.get_table_storage_location(create_table.fully_qualified_table_name)
        create_table_sql: str = (
            f"CREATE TABLE{if_not_exists_sql} {table_name} (\n{columns_sql}\n)\n"
            f"LOCATION '{location}'\n"
            "TBLPROPERTIES ('table_type'='ICEBERG', 'format'='parquet')"
        )
        return create_table_sql + (";" if add_semicolon else "")

    def _build_iceberg_create_table_column(self, create_table_column: CREATE_TABLE_COLUMN) -> str:
        if create_table_column.default is not None:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support a column DEFAULT on a transactional table: "
                f"Athena's Iceberg DDL has none, got one on {create_table_column.name!r}"
            )
        column_name_sql: str = self._quote_column_for_create_table(create_table_column.name)
        iceberg_type_name: Optional[str] = self._ICEBERG_COLUMN_TYPE_NAMES.get(
            self.format_metadata_data_type(create_table_column.type.name)
        )
        column_type_sql: str = iceberg_type_name or self._build_create_table_column_type(create_table_column)
        return f"\t{column_name_sql} {column_type_sql}"

    def _build_update_sql(self, update: UPDATE) -> str:
        if update.from_elements:
            return self._build_update_from_sql(update)
        if update.alias:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support UPDATE with an alias and no from_elements: "
                f"Athena's UPDATE takes no target alias"
            )
        return super()._build_update_sql(update)

    def _build_update_from_sql(self, update: UPDATE) -> str:
        """Athena's UPDATE reads no other table, so this one is a MERGE from it on the WHERE. The caller
        guarantees at most one of its rows per target row: a target row matching two fails the MERGE with
        MERGE_TARGET_ROW_MULTIPLE_MATCHES."""
        if len(update.from_elements) != 1 or type(update.from_elements[0]) is not FROM:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support UPDATE with from_elements other than one table: "
                f"it renders as a MERGE, which reads one"
            )
        if update.where is None:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support UPDATE with from_elements and no where: "
                f"the where is the MERGE's join condition"
            )
        lines: list[str] = [
            f"MERGE INTO {self._build_statement_target_sql(update.fully_qualified_table_name, update.alias)}",
            f"USING {self._build_from_part(update.from_elements[0])}",
            f"ON ({self.build_expression_sql(update.where.condition)})",
            f"WHEN MATCHED THEN UPDATE SET {self._build_assignments_sql(update.assignments)}",
        ]
        return "\n".join(lines)

    def _build_delete_sql(self, delete: DELETE) -> str:
        if delete.using_elements:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support DELETE with using_elements: "
                f"Athena's DELETE has no USING clause"
            )
        if delete.alias:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support DELETE with an alias: Athena's DELETE takes no target alias"
            )
        return super()._build_delete_sql(delete)

    def _build_upsert_sql(self, upsert: UPSERT) -> str:
        return self._build_merge_sql(upsert, self._build_upsert_rows_sql(upsert))

    def _build_upsert_via_select_sql(self, upsert_via_select: UPSERT_VIA_SELECT) -> str:
        # A WITH stays inside the USING subquery.
        select_sql: str = self.build_select_sql(upsert_via_select.select_elements, add_semicolon=False)
        return self._build_merge_sql(upsert_via_select, select_sql)

    def _build_upsert_rows_sql(self, upsert: UPSERT) -> str:
        """The rows as VALUES, each value rendered as INSERT INTO renders it: Trino's VALUES takes
        expressions."""
        if not upsert.values:
            raise ValueError("An upsert must have at least one row")
        for index, row in enumerate(upsert.values):
            # Athena would refuse the statement without naming the row.
            if len(row.values) != len(upsert.columns):
                raise ValueError(
                    f"An upsert row must have one value per column, got {len(row.values)} for "
                    f"{len(upsert.columns)} in values[{index}]"
                )
        return self._build_insert_into_values_sql(upsert).strip()

    def _build_merge_sql(self, upsert: UPSERT | UPSERT_VIA_SELECT, source_sql: str) -> str:
        """Unmatched duplicate keys all insert, as an Iceberg table enforces no key; with update assignments, a
        target row two incoming rows match fails the MERGE with MERGE_TARGET_ROW_MULTIPLE_MATCHES."""
        target_alias: str = upsert.alias or self._MERGE_DEFAULT_TARGET_ALIAS
        if target_alias.lower() == self._MERGE_SOURCE_ALIAS:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support an upsert target alias {target_alias!r}: "
                f"it names the incoming rows"
            )
        target: str = self.quote_default(target_alias)
        source: str = self.quote_default(self._MERGE_SOURCE_ALIAS)
        column_names: list[str] = [self.quote_default(self._upsert_column_name(column)) for column in upsert.columns]
        columns_sql: str = ", ".join(column_names)
        key_condition_sql: str = " AND ".join(
            f"{target}.{key} = {source}.{key}"
            for key in (self.quote_default(self._upsert_column_name(column)) for column in upsert.key_columns)
        )
        lines: list[str] = [
            f"MERGE INTO {upsert.fully_qualified_table_name} AS {target}",
            f"USING (\n{source_sql}\n) AS {source} ({columns_sql})",
            f"ON ({key_condition_sql})",
        ]
        if upsert.update_assignments:
            lines.append(f"WHEN MATCHED THEN UPDATE SET {self._build_assignments_sql(upsert.update_assignments)}")
        source_values_sql: str = ", ".join(f"{source}.{column_name}" for column_name in column_names)
        lines.append(f"WHEN NOT MATCHED THEN INSERT ({columns_sql}) VALUES ({source_values_sql})")
        return "\n".join(lines)

    @staticmethod
    def _upsert_column_name(column: COLUMN | str) -> str:
        column_name = column.name if isinstance(column, COLUMN) else column
        if not isinstance(column_name, str):
            raise ValueError(f"An upsert column must be named, got {column_name!r}")
        return column_name

    def _build_source_column_sql(self, source_column: SOURCE_COLUMN) -> str:
        return f"{self.quote_default(self._MERGE_SOURCE_ALIAS)}.{self.quote_default(source_column.name)}"

    def _build_timestamp_iso_text_sql(self, timestamp_iso_text: TIMESTAMP_ISO_TEXT) -> str:
        expression_sql: str = self.build_expression_sql(timestamp_iso_text.expression)
        iso_text_sql: str
        if timestamp_iso_text.fractional_seconds:
            # date_format prints milliseconds only. The text of a timestamp(6) has the microseconds, and its one
            # space becomes the T; a date or a millisecond timestamp casts up exactly.
            iso_text_sql = f"replace(CAST(CAST({expression_sql} AS timestamp(6)) AS varchar), ' ', 'T')"
        else:
            # MySQL's format specifiers: %i is the minutes, %s the seconds.
            iso_text_sql = f"date_format({expression_sql}, '%Y-%m-%dT%H:%i:%s')"
        if timestamp_iso_text.utc_suffix:
            # || propagates NULL.
            return f"({iso_text_sql} || '+00:00')"
        return iso_text_sql

    def _build_date_iso_text_sql(self, date_iso_text: DATE_ISO_TEXT) -> str:
        return f"date_format({self.build_expression_sql(date_iso_text.expression)}, '%Y-%m-%d')"

    def _build_to_timezone_sql(self, to_timezone: TO_TIMEZONE) -> str:
        # Athena casts a timestamp with time zone to its UTC wall clock, not the zone's, so the zone's is read
        # back from its text: to the millisecond, the finest field format_datetime prints.
        expression_sql: str = self.build_expression_sql(to_timezone.expression)
        zoned_sql: str = f"at_timezone({expression_sql}, {self.literal_string(to_timezone.timezone)})"
        return f"CAST(format_datetime({zoned_sql}, 'yyyy-MM-dd HH:mm:ss.SSSSSS') AS timestamp)"

    def _build_date_trunc_sql(self, date_trunc: DATE_TRUNC) -> str:
        return f"date_trunc({self.literal_string(date_trunc.unit)}, {self.build_expression_sql(date_trunc.expression)})"

    def _build_regexp_replace_sql(self, regexp_replace: REGEXP_REPLACE) -> str:
        # Every match is replaced. A backreference is $1: Athena drops a backslash one without an error.
        if "\\" in regexp_replace.replacement:
            raise UnsupportedSqlStatementError(
                f"{type(self).__name__} does not support a REGEXP_REPLACE replacement with a backslash: "
                f"Athena drops it silently, a backreference is written $1"
            )
        expression_sql: str = self.build_expression_sql(regexp_replace.expression)
        pattern_sql: str = self.literal_string(regexp_replace.pattern)
        replacement_sql: str = self.literal_string(regexp_replace.replacement)
        return f"regexp_replace({expression_sql}, {pattern_sql}, {replacement_sql})"

    def _build_epoch_seconds_sql(self, epoch_seconds: EPOCH_SECONDS) -> str:
        # Athena's interval holds milliseconds, so a microsecond fraction would be cut.
        raise self._unsupported_sql_statement_error("EPOCH_SECONDS")

    def _build_json_merge_sql(self, json_merge: JSON_MERGE) -> str:
        # No built-in merges two JSON objects, and an Iceberg table keeps JSON as a string.
        raise self._unsupported_sql_statement_error("JSON_MERGE")
